#!/usr/bin/env node
// check-chapters.mjs — mechanical enforcement of the rules the group already wrote down.
//
// Rules come from the repository, never from this file:
//   - the cast is parsed from STYLE.md ("- Character: <Name>")
//   - the legal chapter slots are parsed from outline.md ("- Chapter 01:", "- Chapters 07-18:")
//   - the header fields and the Title/filename rule come from chapters/00-template.md
//   - every chapter must declare "Filename:" and it must name the file it sits in,
//     written either bare ("01-the-low-tide.md") or under chapters/
//     ("chapters/01-the-low-tide.md") — nothing else is accepted
// Amending STYLE.md or outline.md by ordinary proposal therefore keeps this checker correct.
//
// On top of the header rules, the editor's checks in tools/editor-rules.mjs:
//   - cast names and places spelled as in STYLE.md (Cast, Places, Spelling exceptions)
//   - STYLE.md's Banned phrases, in narration (an ERROR)
//   - point of view: no first-person narration, no head-hopping into another cast
//     member's interior, and the FocalCharacter named in the chapter
//   - chapters matching outline.md: a "  - Title:" the outline fixes (an ERROR), and no
//     empty slot before the last written chapter
//   - the declared TargetWords inside the template's range, and the prose inside the
//     declared TargetWords, unless ContinuityNotes records a "Deviation: ..."
//   - TOC drift: when the scan is chapters/, the committed chapters/INDEX.md and
//     tools/validation/toc.json must be exactly what `npm run toc` writes (an ERROR).
//     Any other scanned directory that holds an INDEX.md has it checked the same way.
//   - orphans: a file in the scanned directory named like a chapter but not .md (an ERROR)
//
// Not chapters, and therefore never checked: 00-template.md, INDEX.md (generated by
// tools/build-toc.mjs) and README.md. See SKIP_FILES below.
//
// Usage:
//   node tools/check-chapters.mjs [directory]        default: chapters/
//   node tools/check-chapters.mjs <dir> --expect-fail  exit 0 only if the scan DID report errors
//   node tools/check-chapters.mjs chapters --report=tools/validation/REPORT.json  write a report
//   node tools/check-chapters.mjs chapters --report tools/validation/REPORT.json  the same, spaced
//   node tools/check-chapters.mjs <dir> --style=PATH --outline=PATH  read the rules from other
//     files than STYLE.md / outline.md (the fixtures in tools/fixtures/editor/ use this)
//   node tools/check-chapters.mjs --strict           warnings fail the run too (the CI gate)
//
// Flags and the positional directory are parsed in a single pass (parseArgs), so a
// --report path is never mistaken for the directory to scan. --report, --style or
// --outline with no usable path exits 2.
//
// Exit code 0 = no errors. Without --strict, warnings never fail the run: the template
// allows a noted deviation from the 2,000-3,000 word range, and the name and POV rules are
// heuristics, so reviewers keep the final say. --strict, which CI runs, fails on warnings
// too: a chapter clears it by fixing the prose, recording "Deviation: ..." in
// ContinuityNotes (word counts), adding a STYLE.md Spelling exception (a real name the
// spelling rule mistakes for a cast name) or waiving one warning rule in the chapter with
// <!-- check-chapters: allow RULE --> once a reviewer has agreed. Notes (outline slots not
// written yet) never fail anything, so the gate passes on a novel that is still being written.
//
// The ONE body rule that does fail the run is the stub floor: a file with fewer than
// STUB_MIN_WORDS words of prose is not a chapter at all, it is the stub
// tools/new-chapter.mjs just wrote. HTML comments (the generator's "Start writing the
// chapter below this line" marker) are stripped before counting, so an untouched stub
// counts as zero words rather than a dozen. Everything between the floor and the
// 2,000-3,000 target stays advisory.

import { readFileSync, readdirSync, existsSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname, basename, resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";
import {
  parseStyle,
  parseOutline,
  parseSpecRange,
  checkNames,
  checkBanned,
  checkPov,
  checkSpecRange,
  checkOutline,
  notesDeviation,
  allowedRules,
  closestName,
} from "./editor-rules.mjs";
import { collectItems, renderIndex, renderJson, OUT_INDEX, OUT_JSON } from "./build-toc.mjs";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const REQUIRED_FIELDS = [
  "Filename",
  "Title",
  "ChapterNumber",
  "TargetWords",
  "ContinuityNotes",
  "FocalCharacter",
];
const HEADER_KEYS = [...REQUIRED_FIELDS];
const MIN_WORDS = 2000;
const MAX_WORDS = 3000;
// Below this, the file holds no prose: it is a stub, and a stub is an error rather
// than a warning. Deliberately far under MIN_WORDS — the group's rule is that a short
// chapter is a judgement call for reviewers, but an EMPTY one is never mergeable.
const STUB_MIN_WORDS = 50;
// Files that live in chapters/ but are not chapters: the template a writer copies,
// the generated index (tools/build-toc.mjs writes chapters/INDEX.md) and a folder
// README. None of them can ever satisfy the NN-title.md rule, so scanning them only
// produced noise — seven errors on a clean tree the moment anyone ran `npm run toc`.
// Compared lowercased, so INDEX.md / index.md are both skipped.
const SKIP_FILES = new Set(["00-template.md", "index.md", "readme.md"]);

// ---------------------------------------------------------------- helpers

function slug(text) {
  // Normalize Unicode (NFKD), strip combining marks (diacritics), then create
  // an ASCII-style slug as before: lower-case, quotes removed, non-alphanumerics
  // become separators and leading/trailing hyphens trimmed.
  return String(text)
    .normalize('NFKD')
    .replace(/\p{M}/gu, '')              // strip diacritic combining marks
    .toLowerCase()
    .replace(/[‘’'"`]/g, "")     // curly and straight quotes just vanish
    .replace(/[^a-z0-9]+/g, "-")           // everything else becomes a separator
    .replace(/^-+|-+$/g, "");
}

function readIfPresent(path) {
  try {
    return existsSync(path) ? readFileSync(path, "utf8") : null;
  } catch {
    return null;
  }
}

// The cast (plus places, banned phrases and spelling exceptions), straight out of STYLE.md.
function readCast(path) {
  const text = readIfPresent(path);
  if (text === null) return { names: [], style: parseStyle(""), source: null };
  const style = parseStyle(text);
  return { names: style.cast, style, source: relative(REPO_ROOT, path) };
}

// The legal chapter numbers (and any fixed titles), straight out of the outline.md chapter mapping.
function readSlots(path) {
  const text = readIfPresent(path);
  if (text === null) return { slots: new Set(), titles: new Map(), source: null };
  const { slots, titles } = parseOutline(text);
  return { slots, titles, source: relative(REPO_ROOT, path) };
}

// Front matter is plain text at the top of the file: the first run of "Key: value"
// lines. First occurrence of a key wins; the body is everything after the last one.
// Accept header keys case-insensitively by mapping lower-cased keys to the
// project's canonical HEADER_KEYS names. This preserves the rest of the code's
// expectation that fields use the canonical names (e.g. "Filename", "Title").
function parseHeader(text) {
  const lines = text.split(/\r?\n/);
  const fields = {};
  let lastHeaderLine = -1;
  const limit = Math.min(lines.length, 40);
  // build a map of lowercased key -> canonical key name
  const KEY_MAP = Object.fromEntries(HEADER_KEYS.map((k) => [k.toLowerCase(), k]));
  for (let i = 0; i < limit; i++) {
    const m = lines[i].match(/^\s*([A-Za-z][A-Za-z ]*?)\s*:\s*(.*)$/);
    if (!m) continue;
    const rawKey = m[1].trim();
    const mapped = KEY_MAP[rawKey.toLowerCase()];
    if (!mapped) continue;
    const key = mapped; // canonical name from HEADER_KEYS
    if (!(key in fields)) fields[key] = m[2].trim();
    lastHeaderLine = i;
  }
  const body = lines.slice(lastHeaderLine + 1).join("\n");
  return { fields, body };
}

// HTML comments are not prose. The generator's marker comment is the whole body of a
// fresh stub, and counting its words made an empty file look like a dozen-word chapter.
function stripComments(body) {
  return String(body).replace(/<!--[\s\S]*?-->/g, " ");
}

function countWords(body) {
  const words = stripComments(body).replace(/[#*_>`]/g, " ").trim().split(/\s+/).filter(Boolean);
  return words.length;
}

// ---------------------------------------------------------------- the check

function checkFile(dir, file, cast, slots, seenNumbers, spec) {
  const errors = [];
  const warnings = [];
  const text = readFileSync(join(dir, file), "utf8");
  const { fields, body } = parseHeader(text);
  // line number in the file of the body's first line, minus one, for editor findings
  const bodyOffset = text.split(/\r?\n/).length - body.split(/\r?\n/).length;
  let chapterNumber = null;

  // 1. filename shape
  const nameMatch = file.match(/^(\d{2})-([a-z0-9-]+)\.md$/);
  if (!nameMatch) {
    errors.push(`filename must be NN-title.md (two digits, a hyphen, a lowercase slug): got "${file}"`);
  }
  const fileNumber = nameMatch ? Number(nameMatch[1]) : null;
  const fileSlug = nameMatch ? nameMatch[2] : null;

  // 2. required header fields
  for (const key of REQUIRED_FIELDS) {
    if (!(key in fields) || fields[key] === "") errors.push(`missing header field "${key}:"`);
  }

  // 2b. the Filename header must name this very file.
  // Accepted forms: the bare basename "NN-title.md" or the repository path
  // "chapters/NN-title.md". Any other directory, and any other name, is an error.
  if (fields.Filename) {
    const declared = fields.Filename.trim().replace(/\\/g, "/").replace(/^\.\//, "");
    if (declared) {
      const declaredBase = declared.slice(declared.lastIndexOf("/") + 1);
      const declaredDir = declared.slice(0, declared.length - declaredBase.length).replace(/\/+$/, "");
      if (declaredDir !== "" && declaredDir !== "chapters") {
        errors.push(
          `Filename header "${fields.Filename}" must be written as "${file}" or "chapters/${file}"`
        );
      } else if (declaredBase !== file) {
        errors.push(`Filename header "${fields.Filename}" does not match file "${file}"`);
      }
    }
  }

  // 3. leftover template placeholders anywhere in the header
  for (const [key, value] of Object.entries(fields)) {
    if (/\[[^\]]*\]/.test(value)) errors.push(`header field "${key}:" still holds a bracket placeholder: ${value}`);
  }
  const focal = fields.FocalCharacter || "";
  const focalIsPlaceholder = /\[[^\]]*\]/.test(focal) || /^(protagonist name|chapter title|name)$/i.test(focal);
  if (/^(protagonist name|chapter title|name)$/i.test(focal)) {
    errors.push(`FocalCharacter is a placeholder ("${fields.FocalCharacter}"), not a cast name`);
  }

  // 4. Title slug must equal the filename slug
  if (fields.Title && fileSlug) {
    const titleSlug = slug(fields.Title);
    if (titleSlug !== fileSlug) {
      errors.push(`Title "${fields.Title}" slugs to "${titleSlug}" but the filename says "${fileSlug}"`);
    }
  }

  // 5. ChapterNumber must equal the filename NN, be unique, and sit in an outline slot
  if (fields.ChapterNumber) {
    const raw = fields.ChapterNumber.trim();
    if (!/^\d{1,3}$/.test(raw)) {
      errors.push(`ChapterNumber must be digits: got "${raw}"`);
    } else {
      const n = Number(raw);
      chapterNumber = n;
      if (fileNumber !== null && n !== fileNumber) {
        errors.push(`ChapterNumber ${raw} does not match the filename number ${String(fileNumber).padStart(2, "0")}`);
      }
      if (seenNumbers.has(n)) {
        errors.push(`duplicate ChapterNumber ${raw} — also used by ${seenNumbers.get(n)}`);
      } else {
        seenNumbers.set(n, file);
      }
      if (slots.slots.size && !slots.slots.has(n)) {
        errors.push(`ChapterNumber ${raw} is not a slot in the outline.md chapter mapping`);
      }
    }
  }

  // 6. FocalCharacter must be a named cast member (a placeholder was already reported in 3)
  if (fields.FocalCharacter && !focalIsPlaceholder && cast.names.length && !cast.names.includes(fields.FocalCharacter)) {
    const hint = closestName(fields.FocalCharacter, cast.names);
    errors.push(
      `FocalCharacter "${fields.FocalCharacter}" is not in the STYLE.md Cast (${cast.names.join(", ")})` +
        (hint ? ` — did you mean "${hint}"?` : "")
    );
  }

  // 6b. merge conflict markers anywhere in the file are an error.
  // Unresolved Git conflict markers (<<<<<<<, =======, >>>>>>>) are disruptive
  // and indicate the file was not inspected after a merge. Scan the whole file
  // (header + body) and fail if any of those token sequences appear.
  if (/<<<<<<<|=======|>>>>>>>/.test(text)) {
    errors.push("merge conflict markers present (<<<<<<< / ======= / >>>>>>>)");
  }

  // 6c. TargetWords must be a numeric range like "2000-3000" (hyphen or en‑dash allowed).
  // Accept only a low and a high integer separated by a hyphen or en‑dash, with optional
  // surrounding spaces. Reject free-form values such as "~2000" or "two thousand to three thousand".
  // The parsed low/high — when the header validates — become the bounds section 7 warns
  // against instead of the hardcoded MIN_WORDS/MAX_WORDS, so a chapter that declares a
  // narrower or wider range (an interlude at 800-1200, say) is judged against its own
  // stated target rather than the novel's default.
  let targetLow = null;
  let targetHigh = null;
  if (fields.TargetWords) {
    const m = fields.TargetWords.match(/^\s*(\d+)\s*[-–]\s*(\d+)\s*$/);
    if (!m) {
      errors.push("TargetWords must be a numeric range like '2000-3000'");
    } else {
      const low = Number(m[1]);
      const high = Number(m[2]);
      if (!Number.isFinite(low) || !Number.isFinite(high) || low <= 0 || high <= 0) {
        errors.push("TargetWords must contain positive integers, e.g. '2000-3000'");
      } else if (low > high) {
        errors.push("TargetWords low bound must be less than or equal to the high bound");
      } else {
        targetLow = low;
        targetHigh = high;
      }
    }
  }

  // 7. word count.
  //   - under the stub floor: an ERROR. The header can be perfect and the file still
  //     contain no chapter, which is exactly what tools/new-chapter.mjs leaves behind.
  //   - otherwise outside the chapter's own validated TargetWords range: advisory, per
  //     the template's "note deviations in ContinuityNotes". Falls back to the
  //     2,000-3,000 default only when TargetWords is missing or failed validation above,
  //     so a broken header does not also throw an unrelated word-count warning on top of
  //     its own error.
  //   - a "Deviation: ..." in ContinuityNotes is the template's noted deviation, and
  //     silences both this warning and the words-spec one below.
  const words = countWords(body);
  const lowBound = targetLow !== null ? targetLow : MIN_WORDS;
  const highBound = targetHigh !== null ? targetHigh : MAX_WORDS;
  const deviationNoted = notesDeviation(fields.ContinuityNotes);
  if (words < STUB_MIN_WORDS) {
    errors.push(
      `chapter has no prose (${words} words, floor is ${STUB_MIN_WORDS}): this file is still a stub`
    );
  } else if (!deviationNoted && (words < lowBound || words > highBound)) {
    warnings.push(
      `${words} words, outside the ${lowBound.toLocaleString("en-US")}-${highBound.toLocaleString("en-US")} target — note the deviation as "Deviation: ..." in ContinuityNotes`
    );
  }

  // 8. the editor's checks (tools/editor-rules.mjs). Skipped on a stub, which has no
  //    prose to read and already fails above. A warning rule the chapter waives with
  //    <!-- check-chapters: allow RULE --> is dropped; errors cannot be waived.
  const findings = [];
  if (!deviationNoted) findings.push(...checkSpecRange(targetLow, targetHigh, spec));
  if (words >= STUB_MIN_WORDS) {
    const focalName = focalIsPlaceholder ? "" : fields.FocalCharacter || "";
    findings.push(...checkNames(body, cast.style, bodyOffset));
    findings.push(...checkBanned(body, cast.style, bodyOffset));
    findings.push(...checkPov(body, focalName, cast.style, bodyOffset));
  }
  const allowed = allowedRules(text);
  for (const f of findings) {
    if (f.level === "error") errors.push(f.message);
    else if (f.level === "warn" && !allowed.has(f.rule)) warnings.push(f.message);
  }

  return { errors, warnings, title: fields.Title || null, number: chapterNumber };
}

// ---------------------------------------------------------------- run

// One pass over the command line, so the flags and the positional directory can
// never disagree. Accepted: --expect-fail, --report=PATH, --report PATH (the
// next argument is consumed as the path), and one positional directory.
// Not exported on purpose: this module exits the process when it loads (see the
// bottom of the file), so the CLI test in tools/test-cli.mjs spawns it instead.
function parseArgs(argv) {
  let expectFail = false;
  let reportPath = null;
  let reportAsked = false;
  let strict = false;
  const positional = [];
  // --style / --outline: the same two spellings as --report; a missing path is null.
  const paths = { style: undefined, outline: undefined };

  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    const pathFlag = a.match(/^--(style|outline)(?:=(.*))?$/);
    if (pathFlag) {
      if (pathFlag[2] !== undefined) {
        paths[pathFlag[1]] = pathFlag[2] || null;
      } else {
        const next = argv[i + 1];
        if (next !== undefined && !next.startsWith("--")) {
          paths[pathFlag[1]] = next;
          i++;
        } else {
          paths[pathFlag[1]] = null;
        }
      }
      continue;
    }
    if (a === "--expect-fail") {
      expectFail = true;
      continue;
    }
    if (a === "--strict") {
      strict = true;
      continue;
    }
    if (a === "--report") {
      reportAsked = true;
      const next = argv[i + 1];
      if (next !== undefined && !next.startsWith("--")) {
        reportPath = next;
        i++; // the path belongs to --report, never to the target
      } else {
        reportPath = null;
      }
      continue;
    }
    if (a.startsWith("--report=")) {
      reportAsked = true;
      reportPath = a.slice("--report=".length) || null;
      continue;
    }
    positional.push(a);
  }

  return { expectFail, reportPath, reportAsked, positional, strict, stylePath: paths.style, outlinePath: paths.outline };
}

// Synthetic perFile entries: findings about the scan as a whole rather than one chapter.
// Their keys can never be a legal NN-title.md name; each prints under its label.
const SYNTHETIC = [
  ["__dir__", null], // labelled with the scanned directory's name
  ["__outline__", "outline"],
  ["__toc__", "toc"],
];

function main(argv) {
  const { expectFail, reportPath, reportAsked, positional, strict, stylePath, outlinePath } = parseArgs(argv);

  if (reportAsked && !reportPath) {
    console.error("check-chapters: --report needs a file path, e.g. --report=tools/validation/REPORT.json");
    return 2;
  }
  if (stylePath === null || outlinePath === null) {
    console.error(`check-chapters: --${stylePath === null ? "style" : "outline"} needs a file path`);
    return 2;
  }

  const target = positional[0] ? resolve(REPO_ROOT, positional[0]) : join(REPO_ROOT, "chapters");

  const cast = readCast(resolve(REPO_ROOT, stylePath || "STYLE.md"));
  const slots = readSlots(resolve(REPO_ROOT, outlinePath || "outline.md"));
  const spec = parseSpecRange(readIfPresent(join(REPO_ROOT, "chapters", "00-template.md")));
  if (stylePath && cast.source === null) {
    console.error(`check-chapters: no such style file: ${stylePath}`);
    return 2;
  }
  if (outlinePath && slots.source === null) {
    console.error(`check-chapters: no such outline file: ${outlinePath}`);
    return 2;
  }

  if (!cast.names.length) console.log("note: no cast parsed from STYLE.md — the FocalCharacter check is off");
  if (!slots.slots.size) console.log("note: no chapter slots parsed from outline.md — the slot check is off");

  if (!existsSync(target)) {
    console.error(`check-chapters: no such directory: ${target}`);
    return expectFail ? 0 : 1;
  }

  const files = readdirSync(target)
    .filter((f) => f.toLowerCase().endsWith(".md") && !SKIP_FILES.has(f.toLowerCase()))
    .sort();

  const seenNumbers = new Map();
  const perFile = {};

  const chapters = [];
  for (const file of files) {
    const { errors, warnings, title, number } = checkFile(target, file, cast, slots, seenNumbers, spec);
    // keep the raw lists and the parsed Title; we'll decide how to count and print after parsing flags
    perFile[file] = { errors: [...errors], warnings: [...warnings], title: title || null };
    if (number !== null) chapters.push({ file, number, title });
  }

  // Orphans: a file named like a chapter ("02-the-turn.txt", "03-x.markdown") is never
  // checked or indexed, because only .md files are. Report it rather than skip it.
  const orphans = readdirSync(target, { withFileTypes: true })
    .filter((d) => d.isFile() && /^\d{2}-/.test(d.name) && !d.name.toLowerCase().endsWith(".md"))
    .map((d) => d.name)
    .sort();
  if (orphans.length) {
    perFile["__dir__"] = {
      errors: orphans.map((f) => `[orphan] "${f}" is named like a chapter but is not a .md file, so nothing checks or indexes it`),
      warnings: [],
    };
  }

  // duplicate Title detection: collect normalized titles and warn when a title appears in >1 file
  const titleMap = new Map();
  for (const file of files) {
    const t = perFile[file].title;
    if (!t) continue;
    const key = slug(String(t).trim());
    if (!key) continue;
    const list = titleMap.get(key) || [];
    list.push(file);
    titleMap.set(key, list);
  }
  for (const [key, fileList] of titleMap.entries()) {
    if (fileList.length <= 1) continue;
    for (const file of fileList) {
      const others = fileList.filter((f) => f !== file).join(", ");
      const originalTitle = perFile[file].title || "";
      perFile[file].warnings.push(`duplicate Title "${originalTitle}" also used by: ${others}`);
    }
  }

  // outline.md declares the novel's legal chapter slots and may fix a slot's title.
  // An outline is allowed to reserve chapters nobody has written yet, so the trailing
  // empty slots are a note that never fails a run, strict or not; an empty slot BEFORE
  // the last written chapter is a gap and a warning. Kept as its own perFile-shaped
  // entry ("__outline__") so it rides the same totals, printing and report code as
  // every other file.
  if (slots.slots.size) {
    const outline = checkOutline(chapters, slots);
    for (const [file, list] of outline.perFile) {
      for (const f of list) (f.level === "error" ? perFile[file].errors : perFile[file].warnings).push(f.message);
    }
    if (outline.findings.length) {
      perFile["__outline__"] = {
        errors: outline.findings.filter((f) => f.level === "error").map((f) => f.message),
        warnings: outline.findings.filter((f) => f.level === "warn").map((f) => f.message),
        notes: outline.findings.filter((f) => f.level === "note").map((f) => f.message),
      };
    }
  }

  // TOC drift: what `npm run toc` would write must be what is on disk — and in CI, on
  // disk is what was committed. chapters/ always has an index (both files); another
  // directory is checked only when it holds an INDEX.md of its own. Line endings are
  // normalised so a CRLF checkout is not drift.
  const isRepoChapters = target === join(REPO_ROOT, "chapters");
  const indexPath = join(target, "INDEX.md");
  if (isRepoChapters || existsSync(indexPath)) {
    const items = collectItems(target);
    const expected = [[isRepoChapters ? OUT_INDEX : indexPath, renderIndex(items)]];
    if (isRepoChapters) expected.push([OUT_JSON, renderJson(items)]);
    const tocErrors = [];
    for (const [path, want] of expected) {
      const have = readIfPresent(path);
      const shown = relative(REPO_ROOT, path);
      if (have === null) {
        tocErrors.push(`[toc-drift] ${shown} is missing — run npm run toc and commit it`);
      } else if (have.replace(/\r\n/g, "\n") !== want) {
        tocErrors.push(`[toc-drift] ${shown} does not match the chapter headers — run npm run toc and commit the result`);
      }
    }
    if (tocErrors.length) perFile["__toc__"] = { errors: tocErrors, warnings: [] };
  }

  // Totals
  let errorCount = Object.values(perFile).reduce((s, f) => s + f.errors.length, 0);
  let warningCount = Object.values(perFile).reduce((s, f) => s + f.warnings.length, 0);

  // If strict mode requested and we're not running a self-test, fold warnings into errors
  if (parseArgs && typeof parseArgs === "function") {
    // noop: keeps linter happy about parseArgs reference
  }

  if (typeof strict !== "undefined" && strict && !expectFail) {
    // fold warnings into errors for exit code and the JSON report — over every
    // perFile entry, including the synthetic "__outline__" one, so a strict run
    // makes a missing slot blocking too.
    for (const file of Object.keys(perFile)) {
      const w = perFile[file].warnings || [];
      if (w.length) {
        perFile[file].errors = perFile[file].errors.concat(w);
        perFile[file].warnings = [];
      }
    }
    errorCount += warningCount;
    warningCount = 0;
  }

  const filesWithErrors = files.filter((f) => perFile[f].errors && perFile[f].errors.length);

  // Print results. In strict mode warnings are shown as ERROR lines unless we're
  // in expectFail (self-test) mode where warnings must be ignored.
  for (const file of files) {
    const { errors, warnings } = perFile[file];
    if ((!errors || !errors.length) && (!warnings || !warnings.length)) {
      console.log(`ok    ${file}`);
      continue;
    }
    for (const e of errors || []) console.log(`ERROR ${file}: ${e}`);
    if (warnings && warnings.length) {
      if (strict && !expectFail) {
        for (const w of warnings) console.log(`ERROR ${file}: ${w}`);
      } else {
        for (const w of warnings) console.log(`warn  ${file}: ${w}`);
      }
    }
  }

  // The synthetic entries print as their own line(s) — the outline, the TOC and the
  // directory are not scanned files, so they never get an "ok" line and never count
  // toward files.length above. Strict mode has already moved their warnings to errors.
  for (const [key, label] of SYNTHETIC) {
    const entry = perFile[key];
    if (!entry) continue;
    const name = label || `${basename(target)}/`;
    for (const e of entry.errors || []) console.log(`ERROR ${name}: ${e}`);
    for (const w of entry.warnings || []) console.log(`warn  ${name}: ${w}`);
    for (const n of entry.notes || []) console.log(`note  ${name}: ${n}`);
  }

  console.log(
    `\nchecked ${files.length} chapter file(s) in ${basename(target)}/ — ` +
      `${errorCount} error(s), ${warningCount} warning(s)`
  );

  const summary = `checked ${files.length} chapter file(s) in ${basename(target)}/ — ${errorCount} error(s), ${warningCount} warning(s)`;

  // If requested, write a machine-readable JSON report with per-file results and totals.
  if (reportPath) {
    try {
      const outPath = resolve(REPO_ROOT, reportPath);
      const outDir = dirname(outPath);
      if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });
      const report = {
        checked: files.length,
        errorCount,
        warningCount,
        files: perFile,
        summary,
      };
      // In strict mode, report should reflect warnings folded into errors for external tooling.
      if (typeof strict !== "undefined" && strict && !expectFail) {
        // recompute counts to be safe
        report.errorCount = Object.values(perFile).reduce((s, f) => s + f.errors.length, 0);
        report.warningCount = 0;
      }
      writeFileSync(outPath, JSON.stringify(report, null, 2) + "\n", "utf8");
      console.log(`wrote report ${outPath}`);
    } catch (err) {
      console.error("failed to write report:", err && err.message ? err.message : String(err));
      // continue — do not change exit code for a failed write
    }
  }

  // Self-test convention: a fixture whose filename contains "broken" MUST produce
  // errors, and every other fixture MUST NOT. Warnings (word count) are ignored,
  // because fixtures are deliberately short.
  if (expectFail) {
    const expected = files.filter((f) => f.includes("broken"));
    const missed = expected.filter((f) => !filesWithErrors.includes(f));
    const falseAlarms = filesWithErrors.filter((f) => !f.includes("broken"));
    for (const f of missed) console.log(`self-test FAILED: ${f} should have been flagged and was not.`);
    for (const f of falseAlarms) console.log(`self-test FAILED: ${f} is a clean fixture but was flagged.`);
    if (!expected.length) console.log("self-test FAILED: no broken fixture found to exercise the checker.");
    if (missed.length || falseAlarms.length || !expected.length) return 1;
    console.log("self-test passed: the broken fixture was flagged and the clean fixture was not.");
    return 0;
  }
  return errorCount > 0 ? 1 : 0;
}

// Restore the CLI behaviour expected by other tooling: exit the process
// with the numeric code returned by main(). This line was accidentally removed
// in a previous PR; restoring it keeps npm scripts and CI/sh shells seeing
// the checker's intended exit status.
process.exit(main(process.argv.slice(2)));
